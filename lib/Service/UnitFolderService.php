namespace OCA\Domus\Service;

use OCA\Domus\Db\Unit;
use OCA\Domus\Exception\ResourceNotFoundException;
use OCA\Domus\Exception\ConflictException;
use OCP\Files\{Folder, IRootFolder};
use OCP\IL10N;

/** Resolve migrated folders in the current actor's mount namespace, never the creator's. */
class UnitFolderService {
    public function __construct(
        private IRootFolder $root,
        private IL10N $l10n,
        private ?ManagementAccessContext $context = null,
        private ?TeamIntegrationService $teams = null,
    ) {}

    /** Bind new Team units to a dedicated folder in the actor's Team mount. */
    public function initialize(Unit $unit, string $userId): void {
        $teamId = $this->context?->activeTeamId();
        if ($teamId === null) return;

        $details = $this->teams?->getTeamFolder($teamId);
        if (empty($details['mountPoint'])) {
            throw new ConflictException($this->l10n->t('This Team has no accessible Team folder.'));
        }
        $folder = $this->root->getUserFolder($userId)->get(trim($details['mountPoint'], '/'));
        if (!$folder instanceof Folder || !$folder->isReadable() || !$folder->isCreatable()) {
            throw new ConflictException($this->l10n->t('This Team has no accessible Team folder.'));
        }

        // The default path is generated by DocumentPathService, never imported verbatim.
        $segments = explode('/', trim($unit->getDocumentPath(), '/'));
        $name = array_pop($segments);
        foreach ($segments as $segment) {
            $node = $folder->nodeExists($segment) ? $folder->get($segment) : $folder->newFolder($segment);
            if (!$node instanceof Folder || !$node->isReadable() || !$node->isCreatable()) {
                throw new ConflictException($this->l10n->t('The unit folder is not writable.'));
            }
            $folder = $node;
        }
        // Repeated imports must not share a document directory with an existing unit.
        $baseName = mb_strcut($name, 0, 255, 'UTF-8');
        $name = $baseName;
        for ($suffix = 2; $folder->nodeExists($name); $suffix++) {
            $ending = ' (' . $suffix . ')';
            $name = mb_strcut($baseName, 0, 255 - strlen($ending), 'UTF-8') . $ending;
        }
        $folder = $folder->newFolder($name);
        $unit->setDocumentPath($this->path($userId, $folder));
        $unit->setDocumentFolderId((int)$folder->getId());
    }

    public function byId(string $userId, int $id): Folder {
        foreach ($this->root->getUserFolder($userId)->getById($id) as $node) {
            if ($node instanceof Folder && $node->isReadable()) return $node;
        }
        throw new ResourceNotFoundException($this->l10n->t('The unit folder is not accessible.'));
    }

    public function path(string $userId, Folder $folder): string {
        $path = $this->root->getUserFolder($userId)->getRelativePath($folder->getPath());
        if ($path === null || $path === '') {
            throw new \InvalidArgumentException($this->l10n->t('Select a dedicated unit folder.'));
        }
        return $path;
    }

    public function refreshPath(Unit $unit, string $userId): void {
        if ($unit->getDocumentFolderId()) {
            $unit->setDocumentPath($this->path($userId, $this->byId($userId, (int)$unit->getDocumentFolderId())));
        }
    }

    public function selectedFolderId(string $userId, string $path): int {
        $folder = $this->root->getUserFolder($userId)->get(trim($path, '/'));
        if (!$folder instanceof Folder || !$folder->isCreatable()) {
            throw new \InvalidArgumentException($this->l10n->t('The unit folder is not writable.'));
        }
        $this->path($userId, $folder);
        return (int)$folder->getId();
    }
}
