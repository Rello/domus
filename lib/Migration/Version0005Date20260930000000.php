namespace OCA\Domus\Migration;

use Closure;
use OCP\DB\ISchemaWrapper;
use OCP\Migration\IOutput;
use OCP\Migration\SimpleMigrationStep;

/** Team ownership is stored on data rows, so remove the redundant lookup table. */
class Version0005Date20260930000000 extends SimpleMigrationStep {
    public function changeSchema(IOutput $output, Closure $schemaClosure, array $options): ?ISchemaWrapper {
        $schema = $schemaClosure();
        if ($schema->hasTable('domus_owner_team')) {
            $schema->dropTable('domus_owner_team');
        }
        return $schema;
    }
}
